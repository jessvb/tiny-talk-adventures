    private val patterns: Map<String, Pattern> = knownAnimals.mapValues { (_, aliases) ->
        Pattern.compile(
            "\\b(?:${aliases.joinToString("|") { Pattern.quote(it) }})\\b",
            Pattern.CASE_INSENSITIVE or Pattern.UNICODE_CASE or Pattern.UNICODE_CHARACTER_CLASS,
        )
    }

    /** Multi-word aliases first ("sea turtle" must not resolve to "turtle"); ties alphabetical. */
    private val detectionOrder: List<String> = knownAnimals.keys.sortedWith(
        compareByDescending<String> { c -> knownAnimals.getValue(c).maxOf { it.split(" ").size } }
            .thenBy { it },
    )

    fun findNewAnimal(transcript: String, excluding: Collection<String>): String? {
        val excluded = excluding.toSet()
        for (canonical in detectionOrder) {
            if (canonical in excluded) continue
            if (patterns.getValue(canonical).matcher(transcript).find()) return canonical
        }
        return null
    }

    fun extractFacts(c: AnimalCharacteristics): List<String> {
        val facts = mutableListOf<String>()
        fun addFact(value: String?, template: (String) -> String) {
            val v = value?.trim()
            if (v.isNullOrEmpty()) return
            val fact = template(v)
            if (Safety.isSafe(fact)) facts.add(fact)
        }
        addFact(c.mostDistinctiveFeature) { "its most distinctive feature is $it" }
        addFact(c.topSpeed) { "it can move as fast as $it" }
        addFact(c.diet) { "its diet is $it" }
        addFact(c.habitat) { "it lives in $it" }
        addFact(c.slogan) { it }
        addFact(c.color) { "its coloring is $it" }
        addFact(c.groupBehavior) { "its group behavior is $it" }
        addFact(c.lifespan) { "its lifespan is $it" }
        return facts
    }
